def region_blocks(v, region, topic, points, children, near, parent_name):
    full, short, partner = region["path_name"], region["short_name"], v["ui"]["partner"]
    key = f"{v['slug']}|{region['path_slug']}|{topic}"
    f = dict(full=full, short=short, topic=topic, topicul=j(topic, "을", "를"), partner=partner, parent=parent_name)
    unit = "시·군·구" if region["level"] == 1 else ("구" if children and children[0]["level"] == 3 else "읍·면·동")
    names = [c["short_name"] for c in children]
    rot = int(hashlib.md5(key.encode()).hexdigest(), 16)
    paras = [pick(key + "i", INTRO).format(**f)]
    if names:
        shown = names[rot % len(names):] + names[:rot % len(names)]
        paras.append(pick(key + "c", CHILD).format(short=short, names=", ".join(shown), n=len(names), unit=unit))
    else:
        paras.append(pick(key + "c", NOCHILD).format(**f))
    paras.append(pick(key + "s", SERVE).format(**f))
    body = [pick(key + "p", POINT).format(point=points[rot % len(points)].rstrip("."), **f)]
    if near:
        body.append(pick(key + "n", NEAR).format(parent=parent_name, names=", ".join(near[:8])))
    return [
        {"slot": "summary", "html": ul([f"{full} {topic} 안내 페이지입니다.", pick(key + "a", AD).format(**f)])},
        {"slot": "intro", "html": f"<h2>{short} {topic} 안내</h2>" + p(*paras)},
        {"slot": "body", "html": f"<h2>{short}에서 먼저 확인할 것</h2>" + p(*body)},
    ]


