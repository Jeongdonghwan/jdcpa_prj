def load_dongs(ex):
    """전국 읍면동(data/regions_dong.tsv)을 level 4 지역으로 추가한다(인천은 seed.py 가 이미 넣었다). 지역 페이지의 실데이터(행정구역 목록)가 된다."""
    by_slug = {r["path_slug"]: r for r in db.q("SELECT id, path_slug, path_name, level FROM regions WHERE level IN (2,3)")}
    sido_fix = {"광주": "전남광주", "전남": "전남광주"}
    short = {"서울": "서울", "부산": "부산", "대구": "대구", "대전": "대전", "울산": "울산", "세종": "세종", "경기": "경기", "강원": "강원", "충청북": "충북", "충청남": "충남",
             "전라북": "전북", "전북": "전북", "전라남": "전남", "경상북": "경북", "경상남": "경남", "제주": "제주", "광주": "광주"}
    n = 0
    with open(ROOT / "data" / "regions_dong.tsv", encoding="utf-8") as f:
        for row in csv.DictReader(f, delimiter="\t"):
            if row["시도"].startswith("인천"):
                continue
            sd = next((v for k, v in short.items() if row["시도"].startswith(k)), None)
            sd = sido_fix.get(sd, sd)
            parent = by_slug.get("-".join([sd] + row["시군구"].split())) if sd else None
            if not parent:
                continue
            n += 1
            ex("""INSERT IGNORE INTO regions (parent_id, level, code, slug, short_name, full_name, path_slug, path_name, publish_stage, sort_order)
                  VALUES (%s,4,%s,%s,%s,%s,%s,%s,0,%s)""",
               (parent["id"], f"h{n:08d}", row["읍면동"], row["읍면동"], row["읍면동"], f"{parent['path_slug']}-{row['읍면동']}",
                f"{parent['path_name']} {row['읍면동']}", 100000 + n))
    return n


