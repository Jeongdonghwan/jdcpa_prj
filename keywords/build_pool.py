def sido_short(name):
    for k, v in SIDO_SHORT.items():
        if name.startswith(k):
            return v
    return name


def sgg_base(tail):
    """['수원시','팔달구'] → '수원 팔달구', ['가평군'] → '가평', ['강남구'] → '강남구'"""
    first = tail[0]
    if len(first) > 2 and first[-1] in "시군":
        first = first[:-1]
    return " ".join([first] + tail[1:])


def load_regions():
    """[(label, sido, sgg_full, level)] — label 은 검색어에 쓰는 짧은 지역명(전국에서 유일하게).
    법정동코드로 단계 구분: 뒤 8자리 0 = 시도, 뒤 5자리 0 = 시군구. 읍면동은 regions_dong.tsv 에서 따로 읽는다."""
    sidos, cand = [], []
    with open(os.path.join(ROOT, "data", "regions.tsv"), encoding="utf-8") as f:
        next(f)
        for line in f:
            p = line.split()
            if len(p) < 3 or p[-1] != "존재":
                continue
            code, parts = p[0], p[1:-1]
            if code[2:] == "00000000":
                sidos += ["광주", "전남"] if parts[0].startswith("전남광주") else [sido_short(parts[0])]
                continue
            if code[5:] != "00000":
                continue
            if parts[0].startswith("세종"):
                sidos.append("세종")
                continue
            tail = parts[1:]
            sd = sido_short(parts[0])
            if parts[0].startswith("전남광주"):
                sd = "광주" if tail[0].endswith("구") else "전남"
            cand.append((sgg_base(tail), sd, " ".join(tail)))
    count = Counter([c[0] for c in cand] + sidos)
    out = [(s, s, "", "sido") for s in sidos]
    seen = {o[0] for o in out}
    for base, sd, full in cand:
        label = base if count[base] == 1 else f"{sd} {base}"
        if label in seen:
            continue
        seen.add(label)
        out.append((label, sd, full, "sgg"))
    return out


REGIONS = load_regions()


def load_dongs():
    """[(label, sido, sgg_full, 'dong')] — 동 이름이 전국에서 하나뿐이면 동 이름만, 겹치면 '시군구 동'."""
    rows = []
    path = os.path.join(ROOT, "data", "regions_dong.tsv")
    if not os.path.exists(path):
        return rows
    with open(path, encoding="utf-8") as f:
        next(f)
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) == 3 and "출장소" not in p[2] and "." not in p[2] and "·" not in p[2]:
                rows.append((sido_short(p[0]), p[1], p[2]))
    count = Counter(r[2] for r in rows)
    taken = {r[0] for r in REGIONS}
    out, seen = [], set()
    for sd, sgg, dong in rows:
        base = sgg_base(sgg.split())
        label = dong if count[dong] == 1 and dong not in taken and len(dong) > 2 else f"{base} {dong}"
        if label in seen:
            label = f"{sd} {base} {dong}"
        if label in seen:
            continue
        seen.add(label)
        out.append((label, sd, sgg, "dong"))
    return out


DONGS = load_dongs()


def load_stations():
    """수도권 전철역 이름(data/stations.tsv, 출처: LiF-Lee/Subway_Station_Data 2021-05). '○○역' 으로 쓴다."""
    path = os.path.join(ROOT, "data", "stations.tsv")
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        next(f)
        return [(n.strip() if n.strip().endswith("역") else n.strip() + "역") for n in f if n.strip()]


