# ── 머천트 규칙에서 온 제외 지역 ─────────────────────────────────────────
CLEAN_EXCLUDED_SIDO = {"울산", "광주", "강원", "충남", "전북", "전남", "제주", "경남"}
PIPE_EXCLUDED_SGG = ("연천", "철원", "강화", "옹진", "단양", "울릉")
PIPE_GANGWON_OK = ("원주", "춘천")
ISLAND_SGG = ("울릉", "옹진", "신안", "완도", "진도")  # 철거: 울릉도·남부 일부 섬 제외(신안·완도·진도·옹진은 보수적으로 보류)


def allowed(section, sd, full, level):
    if section == "clean" and sd in CLEAN_EXCLUDED_SIDO:
        return False
    if section == "pipe":
        if any(x in full for x in PIPE_EXCLUDED_SGG):
            return False
        if sd == "강원" and (level == "sido" or not any(x in full for x in PIPE_GANGWON_OK)):
            return False
    if section == "demol" and any(x in full for x in ISLAND_SGG):
        return False
    return True


def regions_for(section, level=None):
    return [(label, lv) for label, sd, full, lv in REGIONS if allowed(section, sd, full, lv) and (level is None or lv == level)]


def dongs_for(section):
    return [label for label, sd, full, lv in DONGS if allowed(section, sd, full, lv)]


def norm(s):
    return re.sub(r"\s+", "", s)


class Pool:
    def __init__(self, vertical):
        self.vertical, self.rows, self.seen = vertical, [], set()

    def add(self, section, ptype, tier, keyword, region="", topic="", mod=""):
        keyword = re.sub(r"\s+", " ", keyword).strip()
        if any(b in keyword for b in BAN[section]):
            return
        k = norm(keyword)
        if k in self.seen:
            return
        self.seen.add(k)
        self.rows.append((keyword, self.vertical, section, ptype, tier, region, topic, mod))

    def topics(self, section, items, tier="A", ptype="topic"):
        for t in items:
            self.add(section, ptype, tier, t, topic=t)

    def x(self, section, ptype, tier, left, right, fmt="{a} {b}"):
        """왼쪽(상황·대상·사례) × 오른쪽(주제) 조합."""
        for a, b in itertools.product(left, right):
            self.add(section, ptype, tier, fmt.format(a=a, b=b), topic=b, mod=a)

    def rx(self, section, items, tier_sido="A", tier_sgg="A", ptype="region_topic"):
        """시도·시군구 × 주제."""
        for (label, level), t in itertools.product(regions_for(section), items):
            self.add(section, ptype, tier_sido if level == "sido" else tier_sgg, f"{label} {t}", label, t)

    def rxx(self, section, mods, items, tier_sido="B", tier_sgg="C", ptype="region_mod_topic", level=None):
        """시도·시군구 × 상황 × 주제."""
        for (label, lv), m, t in itertools.product(regions_for(section, level), mods, items):
            self.add(section, ptype, tier_sido if lv == "sido" else tier_sgg, f"{label} {m} {t}", label, t, m)

    def dx(self, section, items, tier="C", ptype="dong_topic"):
        """읍면동 × 주제."""
        for label, t in itertools.product(dongs_for(section), items):
            self.add(section, ptype, tier, f"{label} {t}", label, t)

    def sx(self, section, items, tier="C", ptype="station_topic"):
        """전철역 × 주제."""
        for label, t in itertools.product(STATIONS, items):
            self.add(section, ptype, tier, f"{label} {t}", label, t)

    def dxx(self, section, mods, items, tier="D", ptype="dong_mod_topic"):
        """읍면동 × 상황 × 주제 (최대 확장용, 4순위)."""
        for label, m, t in itertools.product(dongs_for(section), mods, items):
            self.add(section, ptype, tier, f"{label} {m} {t}", label, t, m)

    def write(self):
        path = os.path.join(HERE, f"pool_{self.vertical}.csv")
        with open(path, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.writer(f)
            w.writerow(["keyword", "vertical", "section", "page_type", "tier", "region", "topic", "modifier"])
            w.writerows(self.rows)
        return path


